"use client";

import { redirect, usePathname } from "next/navigation";
import { AcademicRecordsPage, GroupAcademicPage } from "@/components/academic/AcademicPages";
import { AnalysisPage } from "@/components/analysis/AnalysisPage";
import { ProfitabilityPage } from "@/components/admin/AdminPages";
import { GoogleSettingsPage } from "@/components/admin/GoogleSettingsPage";
import { AttendanceMatrixPage, AttendancePage, AttendanceRosterPage, RecordedSessionsPage } from "@/components/attendance/AttendancePages";
import { CollectionsPage, OutstandingBalancesPage, PaymentLedgerPage } from "@/components/collections/CollectionsPages";
import { CertificatesPage } from "@/components/certificates/CertificatesPage";
import { DashboardPage } from "@/components/dashboard/DashboardPage";
import { GroupRostersPage } from "@/components/groups/GroupRostersPage";
import { GroupDetailPage, TrackDetailPage, TracksGroupsPage } from "@/components/groups/GroupsPages";
import { SessionMaterialsPage } from "@/components/materials/SessionMaterialsPage";
import { LearningResourcesPage } from "@/components/resources/LearningResourcesPage";
import { StudentDocumentsPage } from "@/components/student-documents/StudentDocumentsPage";
import { StudentPlacementPage } from "@/components/groups/TrainingOperationsPage";
import { NewSessionPage, SchedulePage, SessionDetailPage } from "@/components/schedule/SchedulePages";
import { ExpensesPage, PayrollPage, StaffDirectoryPage, StaffProfilePage } from "@/components/staff/StaffPages";
import { StudentProfilePage, StudentsPage } from "@/components/students/StudentsPages";
import { NewStudentRegistrationPage } from "@/components/students/RegistrationPage";
import { Card, LinkButton, PageHeader } from "@/components/ui/primitives";

export function OperationsRouter() {
  const pathname = usePathname(); const parts = pathname.split("/").filter(Boolean);
  if (["/users-permissions", "/imports-audit"].includes(pathname)) redirect("/dashboard");
  if (pathname === "/dashboard") return <DashboardPage/>;
  if (pathname === "/analysis") return <AnalysisPage/>;
  if (pathname === "/students") return <StudentsPage/>;
  if (pathname === "/students/new") return <NewStudentRegistrationPage/>;
  if (pathname === "/student-placement") return <StudentPlacementPage/>;
  if (parts[0] === "students" && parts[1]) return <StudentProfilePage id={decodeURIComponent(parts[1])}/>;
  if (pathname === "/tracks-groups") return <TracksGroupsPage/>;
  if (pathname === "/group-rosters") return <GroupRostersPage/>;
  if (pathname === "/tracks-groups/student-placement") redirect("/student-placement");
  if (parts[0] === "tracks-groups" && parts[1]) return <TrackDetailPage trackId={decodeURIComponent(parts[1])}/>;
  if (parts[0] === "groups" && parts[1]) return <GroupDetailPage groupId={decodeURIComponent(parts[1])}/>;
  if (pathname === "/schedule") return <SchedulePage/>;
  if (pathname === "/schedule/new") return <NewSessionPage/>;
  if (parts[0] === "schedule" && parts[1]) return <SessionDetailPage sessionId={decodeURIComponent(parts[1])}/>;
  if (pathname === "/attendance") return <AttendancePage/>;
  if (pathname === "/attendance/sessions") return <AttendancePage initialTab="Attendance Sessions"/>;
  if (pathname === "/attendance/form-responses") return <AttendancePage initialTab="Form Responses"/>;
  if (pathname === "/attendance/validation-review") return <AttendancePage initialTab="Validation Review"/>;
  if (pathname === "/attendance/session-review") return <AttendancePage initialTab="Session Review"/>;
  if (pathname === "/attendance/roster") return <AttendanceRosterPage/>;
  if (pathname === "/attendance/matrix") return <AttendanceMatrixPage/>;
  if (pathname === "/attendance/recorded-sessions") redirect("/recorded-sessions");
  if (pathname === "/recorded-sessions") return <RecordedSessionsPage/>;
  if (pathname === "/session-materials") return <SessionMaterialsPage/>;
  if (pathname === "/resources") return <LearningResourcesPage/>;
  if (pathname === "/student-documents") return <StudentDocumentsPage/>;
  if (pathname === "/academic-records") return <AcademicRecordsPage/>;
  if (pathname === "/certificates") return <CertificatesPage/>;
  if (parts[0] === "academic-records" && parts[1]) return <GroupAcademicPage groupId={decodeURIComponent(parts[1])}/>;
  if (pathname === "/collections") return <CollectionsPage/>;
  if (pathname === "/collections/ledger") return <PaymentLedgerPage/>;
  if (pathname === "/collections/outstanding") return <OutstandingBalancesPage/>;
  if (pathname === "/staff-payroll") return <StaffDirectoryPage/>;
  if (parts[0] === "staff-payroll" && parts[1]) return <StaffProfilePage staffId={decodeURIComponent(parts[1])}/>;
  if (pathname === "/payroll") return <PayrollPage/>;
  if (pathname === "/expenses") return <ExpensesPage/>;
  if (pathname === "/profitability") return <ProfitabilityPage/>;
  if (pathname === "/settings") return <GoogleSettingsPage/>;
  return <><PageHeader title="Page not found" description="This route is not part of the internal TechTrek operations MVP."/><Card className="p-8"><LinkButton href="/dashboard">Return to Dashboard</LinkButton></Card></>;
}
